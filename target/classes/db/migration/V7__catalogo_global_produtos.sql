-- ── Tabela de categorias do catálogo ────────────────────────
CREATE TABLE catalogo_categoria (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome        VARCHAR(100) NOT NULL UNIQUE,
    segmento    VARCHAR(50)  NOT NULL,
    icone       VARCHAR(10),
    ordem       INT          NOT NULL DEFAULT 0
);

-- ── Tabela principal do catálogo ────────────────────────────
CREATE TABLE produto_catalogo (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    categoria_id    UUID REFERENCES catalogo_categoria(id),
    nome            VARCHAR(200) NOT NULL,
    codigo_barras   VARCHAR(50),
    ncm             VARCHAR(10),
    unidade         VARCHAR(10)     NOT NULL DEFAULT 'UN',
    preco_sugerido  NUMERIC(12,2)   NOT NULL DEFAULT 0.00,
    descricao       TEXT,
    ativo           BOOLEAN         NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_catalogo_categoria ON produto_catalogo(categoria_id);
CREATE INDEX idx_catalogo_nome      ON produto_catalogo USING gin(to_tsvector('portuguese', nome));
CREATE INDEX idx_catalogo_barras    ON produto_catalogo(codigo_barras);

